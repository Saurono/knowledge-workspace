/** Vite explicit sandbox smoke; never point this at a production workspace. */
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright-core')
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']})
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 const errors=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto(process.env.WORKSPACE_BASE_URL||'http://127.0.0.1:1420/preview.html')
 await page.getByText('交互预览',{exact:true}).waitFor()
 await page.getByRole('button',{name:'Wiki',exact:true}).click()
 await page.getByRole('tab',{name:'编辑模式',exact:true}).click()
 const labels=await page.evaluate(async()=>{const {default:i18n}=await import('/src/i18n/index.ts');return {editRaw:i18n.t('editor.editRaw'),raw:i18n.t('editor.rawMarkdownEditor')}})
 await page.getByTitle(labels.editRaw,{exact:true}).click()
 const editor=page.getByRole('textbox',{name:labels.raw,exact:true})
 await editor.waitFor()
 const before = await editor.inputValue()
 await page.evaluate(async()=>{
  const {useWikiStore}=await import('/src/stores/wiki-store.ts')
  const {writeFile}=await import('/src/commands/fs.ts')
  await writeFile(useWikiStore.getState().selectedFile,'# External revision\n\nKeep external content')
 })
 await editor.fill(before+'\n\nUnsaved conflict draft')
 await page.getByRole('alert').filter({hasText:'文件已被其他操作修改'}).waitFor()
 if(!(await editor.inputValue()).includes('Unsaved conflict draft'))throw new Error('Conflict draft lost')
 const persisted=await page.evaluate(async()=>{
  const {useWikiStore}=await import('/src/stores/wiki-store.ts')
  const {readFile}=await import('/src/commands/fs.ts')
  return readFile(useWikiStore.getState().selectedFile)
 })
 if(!persisted.includes('Keep external content')||persisted.includes('Unsaved conflict draft'))throw new Error('External revision overwritten')
 await page.getByRole('button',{name:'放弃草稿并加载最新版本',exact:true}).click()
 await page.getByText('Keep external content',{exact:true}).waitFor()
 if(errors.length)throw new Error(errors.join('\n'))
 console.log(JSON.stringify({result:'passed',pageErrors:errors,checks:['conflict detected','draft retained','external revision preserved','explicit reload']}))
} finally {await browser.close()}
